TOP='PriorityMuxModule_25'
SOURCE_SHA256='715a865bece5513803c58422766b2b499b12dca89a5d829a66f5524e8da95a52'
INPUTS=('s2_new_bit_0_sel','s2_new_bit_0_src','s1_new_bit_0_sel','s1_new_bit_0_src',
        's3_new_bit_0_sel','s3_new_bit_0_src','redirect_new_bit_0_src')
ALPHABET='01xz'
# Independently authored boundary expectations, in exact INPUTS order.
DIRECTED={'0000000':'0','1111111':'1','xxxxxxx':'x','zzzzzzz':'z',
          '1z10110':'z','001z110':'z','00001z0':'z','0x0z01z':'z',
          'x111000':'1','zz0000z':'z','x011000':'x','zx0000z':'x',
          'xz1x000':'x','00x1110':'1','0000zzz':'z','0000x01':'x'}


def mux(condition,yes,no):
    """IEEE scalar ?: truth rule, independent of converter tag/value operations."""
    if any(c not in ALPHABET for c in (condition,yes,no)):raise ValueError('scalar 01xz required')
    if condition=='1':return yes
    if condition=='0':return no
    return yes if yes==no else 'x'


def oracle(values,coverage=None):
    s2,d2,s1,d1,s3,d3,redirect=(values[n] for n in INPUTS)
    low=mux(s3,d3,redirect);middle=mux(s1,d1,low);result=mux(s2,d2,middle)
    if coverage is not None:
        for key,c,y,n in [('s3',s3,d3,redirect),('s1',s1,d1,low),('s2',s2,d2,middle)]:
            coverage[key][c+':'+y+':'+n]+=1
    return {'out_res':result}


def corpus():
    return [{'inputs':dict(zip(INPUTS,values))} for values in itertools.product(ALPHABET,repeat=len(INPUTS))]


def inventory(source):
    s=load_parser();sm=s.SourceManager();tree=s.syntax.SyntaxTree.fromFile(str(source),sm)
    options=s.ast.CompilationOptions();options.topModules={TOP}
    compilation=s.ast.Compilation(s.Bag([options]));compilation.addSyntaxTree(tree)
    root=compilation.getRoot();diagnostics=compilation.getAllDiagnostics()
    if any(d.isError() for d in diagnostics):raise ValueError(s.DiagnosticEngine.reportAll(sm,diagnostics))
    if len(root.topInstances)!=1:raise ValueError('expected one actual top')
    instance=root.topInstances[0];syntax=Counter();conditions=[]
    def visit(node):
        if not isinstance(node,s.syntax.SyntaxNode):return
        kind=str(node.kind).split('.')[-1];syntax[kind]+=1
        if kind=='ConditionalExpression':
            pos=node.sourceRange.start;conditions.append(dict(line=sm.getLineNumber(pos),column=sm.getColumnNumber(pos)))
    tree.root.visit(visit)
    ports=[dict(name=p.name,direction=str(p.direction).split('.')[-1],width=p.type.bitWidth,
                signed=bool(p.type.isSigned),four_state=bool(p.type.isFourState)) for p in instance.body.portList]
    expected={n:('In',1,False,True) for n in INPUTS};expected['out_res']=('Out',1,False,True)
    if {p['name']:(p['direction'],p['width'],p['signed'],p['four_state']) for p in ports}!=expected:
        raise ValueError('actual module interface differs from pinned experiment contract')
    if syntax['ModuleDeclaration']!=1 or syntax['ConditionalExpression']!=3 or syntax['ContinuousAssign']!=1:
        raise ValueError('actual module structure differs from audit')
    forbidden=('HierarchyInstantiation','AlwaysBlock','AlwaysFFBlock','InitialBlock','FunctionDeclaration','ParameterDeclaration')
    if any(syntax[k] for k in forbidden):raise ValueError('unexpected dependency/state/parameter')
    return dict(top=TOP,source_sha256=digest(source),ports=ports,syntax=dict(syntax),
                conditional_locations=conditions,dependencies=[],states=[],clock=None,
                generator_comment_record_only='Generated by CIRCT firtool-1.135.0; original generation command not rerun')


def campaign(source,receipt_path,manifest,folder):
    report=dict(status='RUNNING',top=TOP,execution_location='Windows local existing pinned tools',
                scope='One module definition at the pinned RTL hash, settled combinational truth table; not the 256 XSTop instances or arbitrary-delay equivalence.',
                source=str(source),manifest=str(manifest),reference_normalization=False,
                original_rtl_layout='Exact acquired bytes; no firtool normalization or source rewrite')
    write(folder/'summary.json',report)
    try:
        root=_PROJECT_ROOT;harness_hashes={}
        for name in ('scripts/verification/four_state/verify_fourstate_prioritymux.py',
                     'scripts/verification/four_state/verify_fourstate_prioritymux_remote.py',
                     'tests/test_fourstate_prioritymux.py'):
            source_file=root/name;target=folder/'harness-source'/name;target.parent.mkdir(parents=True,exist_ok=True)
            target.write_bytes(source_file.read_bytes());harness_hashes[name]=digest(target)
        report['harness_source_sha256']=harness_hashes;report['invocation']=[sys.executable,*sys.argv]
        receipt=json.loads(receipt_path.read_text(encoding='utf-8'))
        if digest(source)!=SOURCE_SHA256 or receipt['sha256']!=SOURCE_SHA256:raise ValueError('source provenance mismatch')
        write(folder/'input-receipt.json',receipt)
        (folder/'original-input.sv').write_bytes(source.read_bytes())
        report['inventory']=inventory(source);write(folder/'inventory.json',report['inventory'])
        mapping,model_path=load(manifest);ir=json.loads(model_path.read_text(encoding='utf-8'))
        compiled=json.loads((manifest.parent/'lean-check/result.json').read_text(encoding='utf-8'))
        if (manifest.parent/'original.sv').read_bytes()!=source.read_bytes():raise ValueError('converter input snapshot changed')
        if mapping['top']!=TOP or ir['states'] or ir['clock'] is not None or ir.get('arbitrary_inputs'):
            raise ValueError('unexpected model interface/state/arbitrary input')
        if compiled['status']!='PASS' or compiled['exit_code']!=0:raise ValueError('actual Lean compilation missing')
        report['tools']=tools_record(folder/'tools')
        trace=corpus();coverage={n:Counter() for n in ('s2','s1','s3')};expected=[oracle(r['inputs'],coverage) for r in trace]
        if len(trace)!=4**7 or len({tuple(r['inputs'][n] for n in INPUTS) for r in trace})!=4**7:
            raise ValueError('incomplete or duplicate exhaustive corpus')
        lookup={''.join(r['inputs'][n] for n in INPUTS):i for i,r in enumerate(trace)}
        directed=[]
        for bits,value in DIRECTED.items():
            i=lookup[bits]
            if expected[i]!={'out_res':value}:raise ValueError('independent authored boundary disagrees with oracle: '+bits)
            directed.append(dict(sample=i,inputs=bits,expected=value))
        if any(len(c)!=64 for c in coverage.values()):raise ValueError('scalar mux operand coverage incomplete')
        write(folder/'trace.json',trace);write(folder/'oracle.json',expected)
        (folder/'trace.jsonl').write_text(''.join(json.dumps(r)+'\n' for r in trace),encoding='utf-8')
        original=run_rtl(source,mapping,trace,folder/'original-run')
        encoded=run_rtl(manifest.parent/'encoded.sv',mapping,trace,folder/'encoded-run',True)
        lean=simulate(manifest,trace,folder/'lean-run')
        lean_outputs=[r['outputs'] for r in lean]
        comparisons=compare(mapping,original,encoded,lean_outputs)
        decoded=[decode(mapping,r) for r in encoded]
        for label,actual in [('original',original),('encoded',decoded),('lean',lean_outputs)]:
            for i,(a,b) in enumerate(zip(actual,expected)):
                if a!=b:raise ValueError(f'{label} independent oracle mismatch sample {i}: {a} != {b}')
        rails=json.loads((folder/'lean-run/lean/result.json').read_text(encoding='utf-8'))
        if [r['pre'] for r in rails]!=encoded or [r['post'] for r in rails]!=encoded:
            raise ValueError('actual Lean rails differ from encoded RTL')
        histogram=Counter(r['out_res'] for r in original)
        if set(histogram)!=set(ALPHABET):raise ValueError('not all output states observed')
        coverage_report=dict(samples=len(trace),unique_assignments=len(trace),input_bits=7,full_scalar_domain=4**7,
                             all_inputs_four_values={n:dict(Counter(r['inputs'][n] for r in trace)) for n in INPUTS},
                             mux_operand_triples={n:dict(c) for n,c in coverage.items()},directed=directed,
                             output_histogram=dict(histogram),
                             scope='Operand-triple coverage derived from independent scalar oracle, not simulator instrumentation or whole-design coverage.')
        write(folder/'coverage.json',coverage_report)
        report.update(status='PRIORITYMUX_THREE_WAY_PASS',samples=len(trace),unique_assignments=len(trace),
                      output_bit_positions=comparisons,independent_oracle_checks=len(trace)*3,
                      exact_encoded_lean_rail_samples=len(trace),functional_nodes=len(ir['nodes']),
                      source_sha256=digest(source),manifest_sha256=digest(manifest),output_histogram=dict(histogram),
                      coverage='coverage.json',conversion_status='COMPILED',lean_compilation=compiled,
                      comparison_status='MATCH_0_1_X_Z_EXACT',first_failure=None,
                      source_snapshot_sha256=json.loads(manifest.read_text(encoding='utf-8'))['source_snapshot_sha256'])
    except Exception:
        report.update(status='FAIL',first_failure=traceback.format_exc())
    report['artifact_sha256']={p.relative_to(folder).as_posix():digest(p) for p in folder.rglob('*') if p.is_file() and p!=folder/'summary.json'}
    write(folder/'summary.json',report);return report


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,required=True);p.add_argument('--receipt',type=Path,required=True)
    p.add_argument('--manifest',type=Path,required=True);p.add_argument('--out',type=Path,required=True)
    a=p.parse_args();folder=fresh_directory(a.out)
    result=campaign(a.source.resolve(),a.receipt.resolve(),a.manifest.resolve(),folder)
    print(json.dumps(dict(status=result['status'],summary=str(folder/'summary.json'),samples=result.get('samples'),first_failure=result.get('first_failure')),ensure_ascii=True))
    return 0 if result['status']=='PRIORITYMUX_THREE_WAY_PASS' else 1


